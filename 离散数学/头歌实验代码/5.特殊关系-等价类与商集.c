#include <stdio.h>

int main() {
    // n: 表示集合 A = {0, 1, 2, ..., n}
    int n;
    scanf("%d", &n);

    // m: 表示模数，用于定义同余关系
    int m;
    scanf("%d", &m);

    /********** Begin **********/
    // 在此区域编写核心代码
    // 1. 外层循环遍历 m 个等价类，每个等价类由一个余数 i (从 0 到 m-1) 代表
    // 2. 内层循环遍历集合 A 中的所有元素 j (从 0 到 n)
    // 3. 在内层循环中，检查元素 j 是否属于由 i 代表的等价类，即 j % m == i
    // 4. 如果是，则输出 j，并后面跟一个空格
    // 5. 外层循环每执行完一次，就代表一个等价类的所有元素都已输出，此时需要换行
    
    // 1.  外层循环遍历 m 个等价类，每个等价类由一个余数 i (从 0 到 m-1) 代表
    for(int i=0; i<m; i++)
    {
        // 2. 内层循环遍历集合 A 中的所有元素 j (从 0 到 n)
        for(int j=0; j<=n; j++)
        {
            // 3. 在内层循环中，检查元素 j 是否属于由 i 代表的等价类，即 j % m == i
            if(j % m == i)
            {
                // 4. 如果是，则输出 j，并后面跟一个空格
                printf("%d ", j);
            }
        }
        // 5. 外层循环每执行完一次，就代表一个等价类的所有元素都已输出，此时需要换行
        printf("\n");
    }
    /********** End **********/

    return 0;
}
//关键在于用外层循环控制每一个等价类，内层循环遍历元素并且判断输出